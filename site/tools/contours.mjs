// Draws the terrain behind ADVISOR's front page: contour lines, a pond and a
// few footpaths, as two static SVG files in ../assets/. The page itself never
// runs this; it is here so the hills can be re-surveyed later.
//
//   node site/tools/contours.mjs
//
// Same seed, same hills. No randomness at page load, so every visitor walks
// the same campus (and nobody's advisor gets lost twice).

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "assets");

// Small deterministic PRNG (mulberry32).
function rng(seed) {
  return () => {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Closed Catmull-Rom curve through points, as cubic Beziers.
function closedPath(pts) {
  const n = pts.length;
  const f = (v) => v.toFixed(1);
  let d = `M${f(pts[0][0])} ${f(pts[0][1])}`;
  for (let i = 0; i < n; i++) {
    const p0 = pts[(i - 1 + n) % n], p1 = pts[i], p2 = pts[(i + 1) % n], p3 = pts[(i + 2) % n];
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += `C${f(c1[0])} ${f(c1[1])} ${f(c2[0])} ${f(c2[1])} ${f(p2[0])} ${f(p2[1])}`;
  }
  return d + "Z";
}

function hill({ cx, cy, rx, ry, levels, seed, tilt = 0 }) {
  const r = rng(seed);
  const ph = [r() * 6.28, r() * 6.28, r() * 6.28, r() * 6.28];
  const drift = [r() * 0.5, r() * 0.5, r() * 0.5];
  const rings = [];
  for (let i = 0; i < levels; i++) {
    const s = 1 - (i / levels) * 0.92;
    const pts = [];
    const steps = 40;
    for (let k = 0; k < steps; k++) {
      const a = (k / steps) * Math.PI * 2;
      const w = 1
        + 0.13 * Math.sin(3 * a + ph[0] + i * drift[0])
        + 0.07 * Math.sin(5 * a + ph[1] - i * drift[1])
        + 0.035 * Math.sin(8 * a + ph[2] + i * drift[2])
        + 0.05 * Math.sin(2 * a + ph[3]);
      const x = Math.cos(a) * rx * s * w;
      const y = Math.sin(a) * ry * s * w;
      // A little lean, and the summit creeps uphill as rings shrink.
      const ct = Math.cos(tilt), st = Math.sin(tilt);
      pts.push([cx + x * ct - y * st + i * 2.2, cy + x * st + y * ct - i * 1.4]);
    }
    rings.push({ d: closedPath(pts), index: i % 5 === 0 });
  }
  return rings;
}

function svg({ w, h, hills, pond, paths }) {
  const lines = [];
  lines.push(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" preserveAspectRatio="xMidYMid slice">`);
  lines.push(`<!-- Generated by site/tools/contours.mjs. Contour interval: one semester. -->`);
  if (pond) {
    lines.push(`<path d="${pond}" fill="#d6e6de" stroke="#0c5449" stroke-opacity="0.35" stroke-width="1.5"/>`);
    lines.push(`<path d="${pond}" fill="none" stroke="#0c5449" stroke-opacity="0.12" stroke-width="10" transform="translate(0 0)"/>`);
  }
  lines.push(`<g fill="none" stroke="#0c5449" stroke-linejoin="round">`);
  for (const hl of hills) {
    for (const ring of hill(hl)) {
      lines.push(`<path d="${ring.d}" stroke-opacity="${ring.index ? 0.26 : 0.13}" stroke-width="${ring.index ? 1.6 : 1}"/>`);
    }
  }
  lines.push(`</g>`);
  if (paths) {
    lines.push(`<g fill="none" stroke="#073a32" stroke-opacity="0.32" stroke-width="1.6" stroke-dasharray="7 5" stroke-linecap="round">`);
    for (const p of paths) lines.push(`<path d="${p}"/>`);
    lines.push(`</g>`);
  }
  lines.push(`</svg>`);
  return lines.join("\n") + "\n";
}

function blob(cx, cy, rx, ry, seed) {
  const r = rng(seed);
  const pts = [];
  for (let k = 0; k < 18; k++) {
    const a = (k / 18) * Math.PI * 2;
    const w = 1 + (r() - 0.5) * 0.22;
    pts.push([cx + Math.cos(a) * rx * w, cy + Math.sin(a) * ry * w]);
  }
  return closedPath(pts);
}

// The big field map: viewBox matches the inline map in index.html (1200 x 700).
writeFileSync(join(out, "terrain-map.svg"), svg({
  w: 1200, h: 700,
  hills: [
    { cx: 760, cy: 150, rx: 260, ry: 150, levels: 11, seed: 7, tilt: -0.15 },
    { cx: 230, cy: 210, rx: 230, ry: 170, levels: 10, seed: 21, tilt: 0.3 },
    { cx: 1060, cy: 520, rx: 210, ry: 170, levels: 9, seed: 5, tilt: 0.5 },
    { cx: 520, cy: 560, rx: 190, ry: 110, levels: 6, seed: 42, tilt: -0.2 },
  ],
  pond: blob(250, 560, 95, 48, 3),
  paths: [
    "M0 470 C140 450 230 420 330 380 S520 330 640 350 S900 410 1200 380",
    "M560 700 C560 600 600 500 620 420 S700 250 760 0",
    "M0 120 C120 160 300 120 420 170",
  ],
}));

// The hero sheet: a wider, calmer slice of the same country.
writeFileSync(join(out, "terrain-hero.svg"), svg({
  w: 1440, h: 900,
  hills: [
    { cx: 1080, cy: 380, rx: 420, ry: 330, levels: 14, seed: 11, tilt: -0.25 },
    { cx: 160, cy: 820, rx: 330, ry: 200, levels: 8, seed: 33, tilt: 0.2 },
    { cx: 420, cy: 40, rx: 300, ry: 140, levels: 6, seed: 9, tilt: 0.1 },
  ],
  paths: ["M0 640 C260 610 520 700 760 640 S1180 520 1440 560"],
}));

